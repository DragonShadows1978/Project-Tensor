#!/usr/bin/env python3
"""GN1-REV2: complete the /tmp mirror so A2's REAL parent/child/scorer run there.

A2's guard() refuses any RUNS outside its own a2/ directory, and a2/ is
read-only for this review. As REV1 did for A1, the mirror holds byte copies of
every file A2's seal pins (tool files, test files, order, source map, pinned
module) plus the arms regenerated by A2's own regenerate_arms.py (Q6). The
mirror's verify_seal() must pass unchanged; that is the identity proof.

Prior art: test doubles / fault injection (Meszaros, xUnit Test Patterns, 2007);
REV1's mirror method (rev1/hostile_scorer.py). Ours: the file selection.
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

REAL = Path(__file__).resolve().parents[3]
A2 = REAL / "artifacts/gn1/a2"
OUT = Path(__file__).resolve().parent
MROOT = Path("/tmp/gn1_rev2_regen/W")
MA2 = MROOT / "artifacts/gn1/a2"
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()


def main():
    assert os.environ.get("CUDA_VISIBLE_DEVICES") == ""
    seal = json.loads((A2 / "staging_seal.json").read_text())
    proof = {}
    for f, digest in seal["tool_files"].items():
        if not (MA2 / f).exists():
            shutil.copyfile(A2 / f, MA2 / f)
        proof["a2/" + f] = sha(MA2 / f) == digest
    for f, digest in seal["test_files"].items():
        (MROOT / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(REAL / f, MROOT / f)
        proof[f] = sha(MROOT / f) == digest
    for rel in ("orders/GN1_A2_REV1_FIXES.md", "artifacts/gn1/engine_sources_after.json"):
        (MROOT / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(REAL / rel, MROOT / rel)
        proof[rel] = sha(MROOT / rel) == sha(REAL / rel)
    # rev1 shim used by A2's cpu_shim.py (read-only copy for probes)
    (MROOT / "artifacts/gn1/rev1").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(REAL / "artifacts/gn1/rev1/gn_emulate.py", MROOT / "artifacts/gn1/rev1/gn_emulate.py")
    code = ("import sys; sys.path.insert(0, %r); import evidence; s = evidence.verify_seal(); "
            "[evidence.verify_arm(a, s) for a in s['arms']]; print('seal+arms verified', len(s['arms']))" % str(MA2))
    r = subprocess.run([sys.executable, "-B", "-c", code], cwd=MA2, capture_output=True, text=True, timeout=300)
    result = dict(all_identical=all(proof.values()), files=proof, verify_seal_exit=r.returncode,
                  verify_out=r.stdout.strip(), verify_err=r.stderr[-1500:])
    (OUT / "mirror_setup.json").write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(dict(all_identical=result["all_identical"], n=len(proof), verify_seal_exit=r.returncode,
                          out=result["verify_out"], err=result["verify_err"])))
    return 0 if result["all_identical"] and r.returncode == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
