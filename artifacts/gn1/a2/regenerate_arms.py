"""Rebuild arms deterministically from the immutable order commit and pin.
Prior art: SHA-256 (NIST 2001), content-addressed reproducible snapshots;
GN1/A1 package staging. A2 uses byte copies, D5 insertions and single-site
mutations; there are no symlinks or builds. Existing different files refuse.
After sealing, every regenerated byte is checked against the seal.
"""
import argparse
import difflib
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
from build_mutants import specs, mutate

TOOL = Path(__file__).resolve().parent
ROOT = TOOL.parents[2]
sha = lambda b: hashlib.sha256(b).hexdigest()


def put(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        assert not path.is_symlink() and path.read_bytes() == data, "existing differing artifact: " + str(path)
    else:
        with path.open("xb") as f:
            f.write(data)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--verify-seal", action="store_true")
    args = parser.parse_args()
    commit = (TOOL / "order_commit.txt").read_text().strip()
    pin = json.loads((TOOL / "engine_pin.json").read_text())
    module = ROOT / pin["module"]
    assert sha(module.read_bytes()) == pin["sha256"]
    prefix = "tensor_cuda/tensor_cuda/"
    names = subprocess.check_output(["git", "ls-tree", "-r", "--name-only", commit, "--", prefix], cwd=ROOT, text=True).splitlines()
    names = [p for p in names if p.endswith(".py")]
    def content(revision, path):
        return subprocess.check_output(["git", "show", revision+":"+path], cwd=ROOT)
    candidate = content(commit, prefix+"nn.py").decode()
    for old, new in json.loads((TOOL / "d5_edits.json").read_text()):
        assert candidate.count(old) == 1
        candidate = candidate.replace(old, new, 1)
    assert candidate == (ROOT / (prefix+"nn.py")).read_text(), "product differs from deterministic D5 source"
    mutants = specs()
    arm_maps = {}
    for arm in ["baseline", "candidate"] + [m["id"] for m in mutants]:
        pkg = TOOL / "arms" / arm / "tensor_cuda"
        files = {}
        for path in names:
            rel = path.removeprefix(prefix)
            data = content("0e1dea3" if arm == "baseline" else commit, path)
            if arm != "baseline" and rel == "nn.py":
                text = candidate if arm == "candidate" else mutate(candidate, next(m for m in mutants if m["id"] == arm))
                data = text.encode()
                if arm != "candidate":
                    row = next(m for m in mutants if m["id"] == arm)
                    put(TOOL / "mutants" / arm / "nn.py", data)
                    diff = "".join(difflib.unified_diff(candidate.splitlines(True), text.splitlines(True), fromfile="candidate/nn.py", tofile=arm+"/nn.py"))
                    put(TOOL / "mutants" / arm / "nn.diff", diff.encode())
                    row["sha256"] = sha(data)
                    row["edit_sites"] = 1
                    row["minimal_runnable_form"] = "one expression at one source site; no multiline edits"
            put(pkg / rel, data)
            files[rel] = sha(data)
        target = pkg / module.name
        if not target.exists():
            shutil.copyfile(module, target)
        assert not target.is_symlink() and sha(target.read_bytes()) == pin["sha256"]
        files[module.name] = pin["sha256"]
        assert not any(p.is_symlink() for p in pkg.parent.rglob("*"))
        arm_maps[arm] = files
    put(TOOL / "mutants.json", (json.dumps(mutants, indent=2)+"\n").encode())
    put(TOOL / "arm_maps.json", (json.dumps(arm_maps, indent=2)+"\n").encode())
    if args.verify_seal:
        seal = json.loads((TOOL / "staging_seal.json").read_text())
        assert arm_maps == seal["arms"], "regenerated arm maps differ from seal"
        assert commit == seal["order_commit"]
    result = dict(passed=True, order_commit=commit, arms=len(arm_maps), mutants=len(mutants),
                  module_copies=len(arm_maps), engine_sha256=pin["sha256"], seal_verified=args.verify_seal,
                  baseline_commit="0e1dea3", python_sources=names, symlinks=0, builds=0)
    output = TOOL / ("regeneration_verified.json" if args.verify_seal else "regeneration_initial.json")
    output.write_text(json.dumps(result, indent=2)+"\n")
    print(json.dumps(result))


if __name__ == "__main__":
    main()
