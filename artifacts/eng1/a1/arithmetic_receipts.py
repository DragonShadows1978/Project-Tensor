"""CPU arithmetic receipts, never an engine numerical run.
Prior art: IEEE754-2019 nearest-even, NumPy; REV1 numerics.py and coverage_gaps.py.
Taken: stored-operand forward comparisons and final-cast witness; ours: all 40 forward/backward rows.
"""
import sys,importlib.util,json,math
from pathlib import Path
import numpy as np
R=Path(__file__).resolve().parents[3];A=R/'artifacts/eng1/a1';T=R/'artifacts/eng1/tool'
sys.path.insert(0,str(T/'arms/candidate/tensor_cuda'))
sp=importlib.util.spec_from_file_location('eng1',R/'tensor_cuda/tests/test_eng1.py');M=importlib.util.module_from_spec(sp);sp.loader.exec_module(M)
rows=[]
with np.errstate(over='ignore',under='ignore',invalid='ignore'):
 for cls in M.E3_CLASSES:
  for dt in M.E3_DTYPES:
   for case in M.E3_CASES:
    x=M.e3_round(M.e3_inputs(cls,case),dt);g=M.e3_round(M._e3_pattern(x.shape,1.1),dt)
    C,_=M._affine_shape(cls,x.shape);w=M.e3_round(1+.1*np.arange(C),dt)
    b=None if cls=='RMSNorm' else M.e3_round(.05*np.arange(C)-.1,dt)
    refs=M.e3_reference(cls,x,w,b,g);emu=M.e3_emulation(cls,dt,x,w,b,g)
    for k,direction in enumerate(('forward','backward')):
     rows.append(dict(cls=cls,dtype=dt,case=case,direction=direction,
      engine_error_vs_float64=None,emulation_error_vs_float64=M.e3_distance(emu[k],refs[k]),
      engine_distance_from_emulation=None,engine_status='not executed; G5 needs GPU',
      emulation_nonfinite=int(np.count_nonzero(~np.isfinite(emu[k]))),
      accuracy_target=M.e3_tolerance(cls,direction,dt,float(np.max(abs(refs[k])))),
      target_label='accuracy targets (not error bounds)',rounding='IEEE754 nearest-even per primitive and dtype store; fp32 reductions and power'))
assert len(rows)==40
reproductions=[]
for cls,dt,expected in [('RMSNorm','float16',0.0156582687232443),('LayerNorm','bfloat16',0.204845083463340)]:
 row=next(x for x in rows if (x['cls'],x['dtype'],x['case'],x['direction'])==(cls,dt,'near_eps','forward'))
 actual=row['emulation_error_vs_float64'];assert abs(actual-expected)<=5e-12
 reproductions.append(dict(cls=cls,dtype=dt,expected=expected,actual=actual,absolute_difference=abs(actual-expected),reproduction_tolerance=5e-12,accuracy_target=row['accuracy_target']))
# Explicit ties, overflow, subnormal and NaN checks of the arithmetic instrument.
np.testing.assert_array_equal(M.e3_round([1+2**-8,1+3*2**-8],'bfloat16'),[1.,1+2**-6])
np.testing.assert_array_equal(M.e3_round([1+2**-11,1+3*2**-11],'float16'),[1.,1+2**-9])
assert np.isnan(M.e3_round(np.nan,'bfloat16')) and np.isinf(M.e3_round(np.inf,'bfloat16'))
assert M.e3_round(2**-25,'float16')==0 and M.e3_round(3*2**-25,'float16')==2**-23
witnesses={}
for dt,(xs,gs,p) in M.E2_NONPOW2.items():
 x=M.e3_round([xs],dt);g=M.e3_round([gs],dt);assert x[0]==xs and g[0]==gs
 power=M.e3_round(np.power(x,p-1),'float32');scaled=M.e3_round(power*p,'float32')
 late=M.e3_round(M.e3_round(g*scaled,'float32'),dt)
 early=M.e3_round(g*M.e3_round(scaled,dt),dt)
 base=M.e3_round(g*M.e3_round(M.e3_round(power,dt)*p,dt),dt)
 ref=M.e2_reference_grad(x,g,p);tol=M.E2_RTOL[dt]*abs(ref)+M.E2_ATOL[dt]
 value=lambda x:float(x[0])
 assert value(abs(late-ref))<=value(tol) and value(abs(early-ref))>value(tol)
 witnesses[dt]=dict(x=xs,upstream=gs,p=p,reference=value(ref),late=value(late),early=value(early),baseline=value(base),
  late_error=value(abs(late-ref)),early_error=value(abs(early-ref)),baseline_error=value(abs(base-ref)),tolerance=value(tol),
  rtol=M.E2_RTOL[dt],atol=M.E2_ATOL[dt],baseline_fails=bool(value(abs(base-ref))>value(tol)),
  M15_fails=(dt=='bfloat16'),evidence_class='IEEE arithmetic prediction; engine execution GPU only')
(A/'e3_emulation.json').write_text(json.dumps(rows,indent=2,allow_nan=False)+'\n')
(A/'review_reproductions.json').write_text(json.dumps(reproductions,indent=2)+'\n')
(A/'e2_witnesses.json').write_text(json.dumps(witnesses,indent=2)+'\n')
(A/'CALLER_CENSUS.md').write_text('Credit: reproduced unchanged itemization from ENG1-REV1 `artifacts/eng1/rev1/CALLER_CENSUS.md`, generated by `census_scope.py`.\n\n'+(R/'artifacts/eng1/rev1/CALLER_CENSUS.md').read_text())
print('40 E3 emulation rows; review reproduction:',reproductions)
print('E2 derived witnesses:',witnesses)
