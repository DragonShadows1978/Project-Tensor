"""APA-MF2: tables.md from the gate JSONs (item 1 real + synthetic). Script: mine."""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, "artifacts/apa_mf2")
out = ["# APA-MF2 tables (generated by scripts/apa_mf2_summary.py from artifacts/apa_mf2/*.json)", ""]
out += ["## Item 1, real captures: selection vs BK4 diagnostic masks (S=8192, p 0.15, causal, 8 heads)", "",
        "| model | layer | L | bulk | before vs h: agreement (mismatch) | after vs h: agreement (mismatch) | after mismatches outside 2e-5 band | max rel gap | after vs a | h vs a | fp32 helper == bf16 sel |",
        "|---|---:|---:|---:|---|---|---:|---:|---:|---:|---|"]
for f in sorted(glob.glob(os.path.join(A, "real/*.json"))):
    r = json.load(open(f))
    for c in r["cells"]:
        b, a = c["before_vs_h"], c["after_vs_h"]
        out.append(f"| {r['model']} | {r['layer']} | {c['L']} | {c['bulk_bits']} | {b['agreement']:.8f} ({b['mismatch']}) | "
                   f"{a['agreement']:.10f} ({a['mismatch']}) | {a.get('outside_tie_band', 0)} | {a.get('max_rel_gap', 0):.2e} | "
                   f"{c['after_vs_a']['mismatch']} | {c['h_vs_a_mismatch']} | {c['fp32_helper_equals_after_bf16_selection']} |")
s = json.load(open(os.path.join(A, "synth_item1.json")))
out += ["", "## Item 1, review cases (before = MF1 A+B, after = MF2, reference = BK4 'h')", "",
        "```", json.dumps(s["review_cases"], indent=1), "```", "",
        "## Item 1, synthetic census (72 cells; mismatch counts over all L x S x 2 heads)", "",
        "| L | S | D | causal | after fp32 vs h | R1-only floor vs h | min row count of mismatches | before bf16 vs h | bf16 call out-of-band | fp16 call vs fp64 (out-of-band) | h vs a | after vs a |",
        "|---:|---:|---:|---|---:|---:|---:|---:|---:|---|---:|---:|"]
for c in s["cells"]:
    out.append(f"| {c['L']} | {c['S']} | {c['D']} | {c['causal']} | {c['after_fp32_vs_h']} | {c['R1_only_floor_vs_h']} | "
               f"{c.get('after_mismatch_min_row_count', '-')} | {c['before_bf16_vs_h']} | {c['bf16_call_vs_h_outside_band']} | "
               f"{c['fp16_call_vs_fp64']} ({c['fp16_call_vs_fp64_outside_band']}) | {c['h_vs_a']} | {c['after_fp32_vs_a']} |")
open(os.path.join(A, "tables.md"), "w").write("\n".join(out) + "\n")
print("WROTE", os.path.join(A, "tables.md"), len(out))
